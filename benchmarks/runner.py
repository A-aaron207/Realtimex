"""
Realtimex Performance Benchmark Suite — Master Runner

Executes all benchmark modules, collects results, and writes a full
Markdown report to benchmarks/reports/YYYYMMDD_HHMMSS_report.md

Usage:
    PYTHONPATH=. python benchmarks/runner.py
"""

from __future__ import annotations

import importlib
import json
import platform
import sys
import time
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from benchmarks.utils import BenchmarkResult, format_table

BENCHMARK_MODULES = [
    "benchmarks.bench_boot",
    "benchmarks.bench_event_bus",
    "benchmarks.bench_module_loader",
    "benchmarks.bench_model_routing",
    "benchmarks.bench_scheduler",
]

REPORT_DIR = Path(__file__).resolve().parent / "reports"


def run_all() -> list[BenchmarkResult]:
    all_results: list[BenchmarkResult] = []

    for mod_name in BENCHMARK_MODULES:
        print(f"\n▶ Running {mod_name} ...", flush=True)
        try:
            mod = importlib.import_module(mod_name)
            results = mod.run()
            all_results.extend(results)
            for r in results:
                print(f"  ✓ {r.name:45}  mean={r.mean:.4f} {r.unit}")
        except Exception as exc:
            print(f"  ✗ {mod_name} FAILED: {exc}")

    return all_results


def build_report(results: list[BenchmarkResult], elapsed_total: float) -> str:
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    uname = platform.uname()

    lines = [
        "# Realtimex Performance Benchmark Report",
        "",
        f"**Generated:** {now}  ",
        f"**Total benchmark time:** {elapsed_total:.1f}s  ",
        f"**Python:** {sys.version.split()[0]}  ",
        f"**OS:** {uname.system} {uname.release}  ",
        f"**Machine:** {uname.machine}  ",
        f"**Processor:** {uname.processor or uname.machine}  ",
        "",
        "---",
        "",
        "## Summary Table",
        "",
        "```",
        format_table(results),
        "```",
        "",
        "---",
        "",
        "## Detailed Results",
        "",
    ]

    sections: dict[str, list[BenchmarkResult]] = {}
    for r in results:
        prefix = r.name.split(".")[0]
        sections.setdefault(prefix, []).append(r)

    for section, section_results in sections.items():
        lines += [f"### {section.replace('_', ' ').title()}", ""]
        for r in section_results:
            lines += [
                f"#### `{r.name}`",
                "",
                f"| Metric | Value |",
                f"|--------|-------|",
                f"| Unit | {r.unit} |",
                f"| Samples | {len(r.samples)} |",
                f"| Mean | **{r.mean:.4f}** |",
                f"| Median | {r.median:.4f} |",
                f"| Std Dev | {r.stdev:.4f} |",
                f"| Min | {r.min:.4f} |",
                f"| Max | {r.max:.4f} |",
                f"| p95 | {r.p95:.4f} |",
                "",
            ]
            if r.metadata:
                lines.append("**Metadata:**")
                lines.append("```json")
                lines.append(json.dumps(r.metadata, indent=2))
                lines.append("```")
                lines.append("")

    lines += [
        "---",
        "",
        "## Performance Assessment",
        "",
        _assess(results),
        "",
        "---",
        "",
        "*Generated by Realtimex Benchmark Suite v1.0*",
    ]

    return "\n".join(lines)


def _assess(results: list[BenchmarkResult]) -> str:
    """Generate a plain-English assessment of the numbers."""
    by_name = {r.name: r for r in results}
    notes = []

    boot = by_name.get("kernel.boot_time")
    if boot:
        verdict = "✅ Excellent" if boot.mean < 0.5 else ("⚠️ Acceptable" if boot.mean < 2.0 else "❌ Slow")
        notes.append(f"- **Boot time** `{boot.mean:.3f}s` — {verdict} (target: <0.5s)")

    shutdown = by_name.get("kernel.shutdown_time")
    if shutdown:
        verdict = "✅ Excellent" if shutdown.mean < 0.3 else ("⚠️ Acceptable" if shutdown.mean < 1.0 else "❌ Slow")
        notes.append(f"- **Shutdown time** `{shutdown.mean:.3f}s` — {verdict} (target: <0.3s)")

    mem = by_name.get("kernel.boot_peak_memory")
    if mem:
        verdict = "✅ Lean" if mem.mean < 50_000 else ("⚠️ Moderate" if mem.mean < 200_000 else "❌ Heavy")
        notes.append(f"- **Boot peak memory** `{mem.mean:,.0f} KB` — {verdict} (target: <50,000 KB)")

    pub = by_name.get("event_bus.publish_latency")
    if pub:
        verdict = "✅ Fast" if pub.p95 < 1.0 else ("⚠️ Acceptable" if pub.p95 < 5.0 else "❌ Slow")
        notes.append(f"- **Event publish p95** `{pub.p95:.3f}ms` — {verdict} (target: <1ms)")

    burst = by_name.get("event_bus.burst_throughput")
    if burst:
        verdict = "✅ High" if burst.mean > 10_000 else ("⚠️ Moderate" if burst.mean > 2_000 else "❌ Low")
        notes.append(f"- **Event burst throughput** `{burst.mean:,.0f} events/s` — {verdict} (target: >10,000/s)")

    rtt = by_name.get("event_bus.subscribe_rtt_latency")
    if rtt:
        verdict = "✅ Fast" if rtt.p95 < 5.0 else ("⚠️ Acceptable" if rtt.p95 < 20.0 else "❌ Slow")
        notes.append(f"- **Event subscribe RTT p95** `{rtt.p95:.3f}ms` — {verdict} (target: <5ms)")

    req = by_name.get("model_gateway.request_latency")
    if req:
        verdict = "✅ Fast" if req.mean < 5.0 else ("⚠️ Acceptable" if req.mean < 20.0 else "❌ Slow")
        notes.append(f"- **Model request latency** `{req.mean:.2f}ms` — {verdict} (target: <5ms simulated)")

    sub = by_name.get("scheduler.task_submission_latency")
    if sub:
        verdict = "✅ Fast" if sub.p95 < 10.0 else ("⚠️ Acceptable" if sub.p95 < 50.0 else "❌ Slow")
        notes.append(f"- **Task submission p95** `{sub.p95:.2f}ms` — {verdict} (target: <10ms)")

    lookup = by_name.get("capability_registry.lookup_latency")
    if lookup:
        verdict = "✅ Fast" if lookup.p95 < 0.1 else ("⚠️ Acceptable" if lookup.p95 < 1.0 else "❌ Slow")
        notes.append(f"- **Capability registry p95** `{lookup.p95:.4f}ms` — {verdict} (target: <0.1ms)")

    return "\n".join(notes) if notes else "No data."


if __name__ == "__main__":
    print("=" * 60)
    print("  Realtimex Performance Benchmark Suite")
    print("=" * 60)

    t0 = time.perf_counter()
    all_results = run_all()
    elapsed = time.perf_counter() - t0

    print(f"\n\n{'=' * 60}")
    print("  RESULTS")
    print("=" * 60)
    print()
    print(format_table(all_results))
    print()
    print("=" * 60)
    print("  ASSESSMENT")
    print("=" * 60)
    print()
    print(_assess(all_results))
    print()

    # Write report
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    report_path = REPORT_DIR / f"{timestamp}_benchmark_report.md"
    report_path.write_text(build_report(all_results, elapsed))
    print(f"\nReport written to: {report_path}")
    print(f"Total benchmark time: {elapsed:.1f}s")
