"""
Validation pipeline for the Realtimex Cognitive Engine.
"""

from __future__ import annotations

from typing import Any

from cognitive.exceptions import ValidationError


class CognitiveValidator:
    """
    Validates recommendations generated by the Reasoning Provider against safety,
    capability, structural, and semantic rules.
    """

    def validate(self, recommendation: Any, decision_type: str, context: dict[str, Any]) -> bool:
        """
        Validate a recommendation under the given context.

        Args:
            recommendation: The recommendation output to validate.
            decision_type: The decision/task category.
            context: Collected context.

        Returns:
            True if the recommendation is valid.

        Raises:
            ValidationError: If the recommendation fails any validation check.
        """
        decision_type_lower = decision_type.lower()

        # 1. Structural Workflow Planning Validation
        if "workflow planning" in decision_type_lower:
            self._validate_workflow_planning(recommendation, context)

        # 2. Safety / Permission Review Validation
        elif "permission review" in decision_type_lower:
            self._validate_permission_review(recommendation, context)

        # 3. Conflict Resolution Validation
        elif "conflict resolution" in decision_type_lower:
            self._validate_conflict_resolution(recommendation, context)

        # 4. Capability Selection Validation
        elif "capability selection" in decision_type_lower:
            self._validate_capability_selection(recommendation, context)

        # 5. Recovery Recommendation Validation
        elif "recovery recommendation" in decision_type_lower:
            self._validate_recovery_recommendation(recommendation, context)

        # Generic Impossible Recommendation Checks
        self._validate_impossible_recommendations(recommendation)

        return True

    def _validate_workflow_planning(self, recommendation: Any, context: dict[str, Any]) -> None:
        """Reject invalid workflows, missing capabilities, unsafe configurations, etc."""
        if not isinstance(recommendation, dict):
            raise ValidationError("Workflow planning recommendation must be a dictionary.")

        steps = recommendation.get("steps")
        if not steps:
            raise ValidationError("Workflow recommendation is missing a 'steps' list or it is empty.")

        if not isinstance(steps, list):
            raise ValidationError("'steps' in workflow planning recommendation must be a list.")

        available_capabilities = set(context.get("available_capabilities", []))
        permissions_map = context.get("permissions", {})

        step_ids = set()
        adj: dict[str, list[str]] = {}

        for step in steps:
            if not isinstance(step, dict):
                raise ValidationError("Each workflow step must be a dictionary.")

            step_id = step.get("step_id")
            capability = step.get("capability")

            if not step_id or not isinstance(step_id, str):
                raise ValidationError("Each workflow step must have a non-empty string 'step_id'.")
            if not capability or not isinstance(capability, str):
                raise ValidationError(f"Step '{step_id}' must have a non-empty string 'capability'.")

            if step_id in step_ids:
                raise ValidationError(f"Duplicate step ID '{step_id}' detected in workflow.")
            step_ids.add(step_id)

            # Check for missing capabilities
            # If available_capabilities is populated, validate against it
            if available_capabilities and capability not in available_capabilities:
                raise ValidationError(
                    f"Impossible recommendation: capability '{capability}' required by step '{step_id}' is missing."
                )

            # Check sandbox/permission safety of the capability step
            # If step specifies it needs unsafe permissions, but sandbox disallows them
            input_data = step.get("input_data", {})
            if capability == "write_file" or capability == "read_file":
                file_path = input_data.get("file_path", "")
                if "../" in file_path or file_path.startswith("/etc") or file_path.startswith("/var"):
                    raise ValidationError(
                        f"Unsafe suggestion: Step '{step_id}' requests access to unsafe file path '{file_path}'."
                    )

            # Capture dependencies for cycle detection
            deps = step.get("dependencies", [])
            if not isinstance(deps, (list, set, frozenset)):
                raise ValidationError(f"Dependencies of step '{step_id}' must be a list or set.")
            adj[step_id] = list(deps)

        # Validate step dependencies point to valid steps
        for step_id, deps in adj.items():
            for dep in deps:
                if dep not in step_ids:
                    raise ValidationError(
                        f"Invalid workflow: Step '{step_id}' depends on non-existent step '{dep}'."
                    )

        # Detect circular dependencies in the workflow DAG
        visited: dict[str, int] = {sid: 0 for sid in step_ids}  # 0=unvisited, 1=visiting, 2=visited

        def dfs(node: str) -> bool:
            visited[node] = 1
            for neighbor in adj.get(node, []):
                if visited[neighbor] == 1:
                    return True  # Cycle detected
                elif visited[neighbor] == 0:
                    if dfs(neighbor):
                        return True
            visited[node] = 2
            return False

        for step_id in step_ids:
            if visited[step_id] == 0:
                if dfs(step_id):
                    raise ValidationError("Invalid workflow: Circular dependency detected in workflow steps.")

    def _validate_permission_review(self, recommendation: Any, context: dict[str, Any]) -> None:
        """Reject unsafe permission approvals."""
        # If recommendation approves but the context contains explicit warnings
        if isinstance(recommendation, str) and "approve" in recommendation.lower():
            task_history = context.get("task", {}).get("history", [])
            for entry in task_history:
                if "security_violation" in str(entry.get("event_type", "")):
                    raise ValidationError("Unsafe suggestion: Approving permissions on task with historical security violations.")

    def _validate_conflict_resolution(self, recommendation: Any, context: dict[str, Any]) -> None:
        """Validate proposed conflict resolutions."""
        if not recommendation:
            raise ValidationError("Conflict resolution recommendation cannot be empty.")

    def _validate_capability_selection(self, recommendation: Any, context: dict[str, Any]) -> None:
        """Validate capability selection choice."""
        if not isinstance(recommendation, dict):
            raise ValidationError("Capability selection recommendation must be a dictionary.")
        selected = recommendation.get("selected_capability")
        if selected:
            available = set(context.get("available_capabilities", []))
            if available and selected not in available:
                raise ValidationError(
                    f"Impossible recommendation: selected capability '{selected}' is not available."
                )

    def _validate_recovery_recommendation(self, recommendation: Any, context: dict[str, Any]) -> None:
        """Validate recovery steps."""
        if not isinstance(recommendation, dict):
            raise ValidationError("Recovery recommendation must be a dictionary.")
        action = recommendation.get("action")
        if not action:
            raise ValidationError("Recovery recommendation must contain an 'action' key.")

    def _validate_impossible_recommendations(self, recommendation: Any) -> None:
        """Verify structural bounds (e.g. no negative values, valid confidence levels)."""
        if isinstance(recommendation, dict):
            cost = recommendation.get("estimated_cost", 0.0)
            if isinstance(cost, (int, float)) and cost < 0:
                raise ValidationError(f"Impossible recommendation: negative cost estimation ({cost}).")
            time_est = recommendation.get("estimated_time", 0.0)
            if isinstance(time_est, (int, float)) and time_est < 0:
                raise ValidationError(f"Impossible recommendation: negative execution time estimation ({time_est}).")
            
            # Check steps if nested
            steps = recommendation.get("steps", [])
            if isinstance(steps, list):
                for step in steps:
                    if isinstance(step, dict):
                        if step.get("estimated_cost", 0.0) < 0:
                            raise ValidationError("Impossible recommendation: step contains negative estimated_cost.")
                        if step.get("estimated_time", 0.0) < 0:
                            raise ValidationError("Impossible recommendation: step contains negative estimated_time.")
